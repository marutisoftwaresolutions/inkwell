using System.Text.RegularExpressions;
using Blog.Web.Models;
using Xunit;

namespace Blog.Tests;

/// <summary>
/// Source-level guards for the v1.0.9 Desk modernization: the admin stylesheet is compiled at build time
/// (no runtime Tailwind), the shell is grouped navigation driven by one list, screens use the shared
/// component vocabulary instead of fixed palette classes or hand-rolled modals, and the layout owns the h1.
/// </summary>
public class DeskModernizationTests
{
    private static string Root()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "Directory.Build.props"))) dir = dir.Parent;
        Assert.NotNull(dir);
        return dir!.FullName;
    }
    private static string Web(string rel) => File.ReadAllText(Path.Combine(Root(), "Blog.Web", rel.Replace('/', Path.DirectorySeparatorChar)));

    /// <summary>Every view that renders inside the Desk layout, plus the partials only the Desk uses.</summary>
    private static IEnumerable<(string Rel, string Text)> DeskViews()
    {
        var views = Path.Combine(Root(), "Blog.Web", "Views");
        foreach (var f in Directory.EnumerateFiles(views, "*.cshtml", SearchOption.AllDirectories))
        {
            var rel = Path.GetRelativePath(views, f).Replace('\\', '/');
            var text = File.ReadAllText(f);
            var isDesk = text.Contains("Layout = \"_AdminLayout\"")
                         || rel.StartsWith("Posts/_") || rel.StartsWith("Backups/_") || rel.StartsWith("NewsletterAdmin/_")
                         || rel is "Shared/_AdminLayout.cshtml" or "Shared/_ListPager.cshtml" or "Shared/_ListSearch.cshtml"
                             or "Shared/_EmptyState.cshtml" or "Shared/_Skeleton.cshtml" or "Shared/_KpiTile.cshtml";
            if (isDesk) yield return (rel, text);
        }
    }

    [Fact]
    public void Desk_and_auth_layouts_use_the_compiled_stylesheet_not_the_runtime_compiler()
    {
        foreach (var layout in new[] { "Views/Shared/_AdminLayout.cshtml", "Views/Shared/_AuthLayout.cshtml" })
        {
            var html = Web(layout);
            Assert.DoesNotContain("lib/tailwindcss/tailwind.js", html);
            Assert.DoesNotContain("tailwind.config", html);
            Assert.Contains("css/desk.css", html);
        }
        Assert.True(File.Exists(Path.Combine(Root(), "Blog.Web", "wwwroot", "css", "desk.css")), "desk.css is generated by tailwind.desk.config.js and committed");
        Assert.True(File.Exists(Path.Combine(Root(), "Blog.Web", "tailwind.desk.config.js")));
        var csproj = Web("Blog.Web.csproj");
        Assert.Contains("tailwind.desk.config.js", csproj);

        // The admin layout no longer loads libraries only the editor or the public site need.
        var admin = Web("Views/Shared/_AdminLayout.cshtml");
        Assert.DoesNotContain("lucide", admin, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("highlight", admin, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void Component_vocabulary_is_defined_once_in_the_desk_source()
    {
        var src = Web("wwwroot/css/desk.src.css");
        foreach (var cls in new[] { ".desk-btn", ".desk-btn-primary", ".desk-btn-outline", ".desk-btn-danger", ".desk-input", ".desk-select", ".desk-textarea",
                                    ".desk-label", ".desk-card", ".desk-table", ".desk-pill", ".desk-empty", ".desk-skeleton", ".desk-kpi", ".desk-nav-link", ".desk-menu", ".desk-tabs" })
            Assert.Contains(cls + " ", src);
        var compiled = Web("wwwroot/css/desk.css");
        Assert.Contains(".desk-btn-primary", compiled);
        Assert.Contains(".desk-nav-group", compiled);
        // Opacity modifiers on token colours compile (they silently produced nothing with the runtime config).
        Assert.Contains("color-mix(in srgb,var(--primary)", compiled);
    }

    [Fact]
    public void Shell_navigation_is_grouped_and_every_item_belongs_to_a_known_group()
    {
        foreach (var item in DeskNavigation.Items)
            Assert.Contains(item.Group, DeskNavigation.GroupOrder);
        Assert.True(DeskNavigation.Items.Select(i => i.Href).Distinct().Count() == DeskNavigation.Items.Count, "duplicate hrefs");

        var layout = Web("Views/Shared/_AdminLayout.cshtml");
        Assert.Contains("data-nav-group=\"@group.Name\"", layout);
        Assert.Contains("data-nav-group-toggle", layout);
        Assert.Contains("id=\"desk-cmdk\"", layout);                 // command palette
        Assert.Contains("data-rail-toggle", layout);                  // collapsible rail
        Assert.Contains("aria-label=\"Breadcrumb\"", layout);
        Assert.DoesNotContain("@inject Blog.Core.Interfaces.IUserRepository", layout); // views never query (DeskShellService does)
        Assert.Contains("DeskShellService", layout);

        var desk = Web("wwwroot/js/inkwell-desk.js");
        foreach (var hook in new[] { "data-nav-group-toggle", "data-rail-toggle", "data-cmdk-open", "desk-cmdk-input", "data-toast-dismiss" })
            Assert.Contains(hook, desk);
    }

    [Fact]
    public void Layout_owns_the_page_title_so_no_desk_view_renders_an_h1()
    {
        var layout = Web("Views/Shared/_AdminLayout.cshtml");
        Assert.Contains("<h1 class=\"desk-page-title\">@title</h1>", layout);
        Assert.Contains("RenderSectionAsync(\"PageActions\"", layout);

        var offenders = DeskViews().Where(v => v.Rel != "Shared/_AdminLayout.cshtml" && Regex.IsMatch(v.Text, "<h1[\\s>]")).Select(v => v.Rel).ToList();
        Assert.True(offenders.Count == 0, "Desk views rendering their own <h1> (the layout renders ViewData[\"Title\"]):\n" + string.Join('\n', offenders));
    }

    [Fact]
    public void No_desk_view_uses_fixed_palette_classes_that_ignore_the_colour_scheme()
    {
        // bg-red-100, text-emerald-700, border-amber-200, dark:… — all bypass desk-tokens.css. Use pill-*/tone-*/desk-* instead.
        var palette = new Regex(@"(?<![\w-])(?:hover:|focus:)?(?:bg|text|border|ring|from|to|decoration)-(?:red|green|amber|yellow|blue|emerald|gray|grey|slate|zinc|neutral|stone|indigo|purple|pink|orange|teal|sky|rose|lime|cyan|violet|fuchsia)-\d{2,3}(?:/\d+)?\b|(?<![\w-])dark:[\w/-]+", RegexOptions.Compiled);
        var offenders = new List<string>();
        foreach (var (rel, text) in DeskViews())
            foreach (Match m in palette.Matches(text))
                offenders.Add(rel + ": " + m.Value);
        Assert.True(offenders.Count == 0, "Fixed palette classes in Desk views:\n" + string.Join('\n', offenders));
    }

    [Fact]
    public void No_desk_view_hand_rolls_a_modal_over_the_shared_dialog()
    {
        // A fixed full-screen overlay with its own buttons has no focus trap or Escape; InkwellDialog.confirm does.
        var offenders = DeskViews()
            .Where(v => Regex.IsMatch(v.Text, "id=\"\\w*[Mm]odal\"[^>]*class=\"[^\"]*fixed inset-0") || v.Text.Contains("id=\"publishModal\""))
            .Select(v => v.Rel).ToList();
        Assert.True(offenders.Count == 0, "Hand-rolled modals:\n" + string.Join('\n', offenders));
        foreach (var editor in new[] { "Views/Posts/Edit.cshtml", "Views/Posts/Create.cshtml" })
            Assert.Contains("InkwellDialog.confirm(", Web(editor));
    }

    [Fact]
    public void Posts_list_uses_the_shared_pager_and_keeps_its_filter_through_writes()
    {
        var view = Web("Views/Posts/Index.cshtml");
        Assert.Contains("<partial name=\"_ListPager\" />", view);
        Assert.Contains("<partial name=\"_EmptyState\" />", view);
        Assert.DoesNotContain("for (int i = 1; i <= Model.TotalPages; i++)", view); // no every-page pager
        var controller = Web("Controllers/PostsController.cs");
        Assert.Contains("ListPaging.Stash(this,", controller);
        Assert.Contains("Delete(Guid id, string? q, string? status, int page = 1)", controller);
        Assert.Contains("RedirectToAction(\"Index\", new { q, status, page })", controller);
    }

    [Fact]
    public void Dashboard_is_a_working_surface_not_a_counter_wall()
    {
        var dash = Web("Views/Dashboard/Index.cshtml");
        Assert.Contains("Needs attention", dash);
        Assert.Contains("Nothing needs you today.", dash);     // honest empty state
        Assert.Contains("<polyline points=\"@points\"", dash);  // 30-day sparkline, no chart library
        Assert.Contains("_KpiTile", dash);
        var controller = Web("Controllers/DashboardController.cs");
        Assert.Contains("LoadWorkingSurfaceAsync", controller);
        Assert.Contains("ViewsPrev7", controller);
    }

    [Fact]
    public void Editors_use_natural_height_on_phones_and_the_sticky_toolbar()
    {
        foreach (var editor in new[] { "Views/Posts/Edit.cshtml", "Views/Posts/Create.cshtml", "Views/Pages/Edit.cshtml", "Views/Pages/Create.cshtml" })
        {
            var html = Web(editor);
            Assert.DoesNotContain("class=\"h-[calc(100vh-8rem)]", html);   // a fixed height left a few lines of canvas under a phone keyboard
            Assert.Contains("md:h-[calc(100vh-7.5rem)]", html);
            Assert.Contains("ViewData[\"HideHeader\"] = true", html);
        }
    }

    [Fact]
    public void Shared_dialog_toast_and_dirty_pill_use_scheme_safe_tokens()
    {
        var dialog = Web("wwwroot/js/inkwell-dialog.js");
        Assert.DoesNotMatch(new Regex(@"\b(bg|text|border)-(red|green|amber|yellow|blue|emerald)-\d{2,3}\b"), dialog);
        Assert.Contains("desk-btn-danger", dialog);
        var css = Web("wwwroot/css/admin.css");
        var pill = css[css.IndexOf("[data-dirty-indicator] {", StringComparison.Ordinal)..];
        pill = pill[..pill.IndexOf("/* ──", StringComparison.Ordinal)];
        Assert.DoesNotMatch(new Regex("#[0-9a-fA-F]{6}"), pill);
        Assert.Contains("var(--warning)", pill);
        // The dead pre-Tailwind component system is gone.
        foreach (var dead in new[] { ".stat-card", ".posts-grid", ".editor-shell", ".modal-overlay", ".media-grid", ".sidebar-brand", ".page-btn" })
            Assert.DoesNotContain(dead + " ", css);
    }
}
